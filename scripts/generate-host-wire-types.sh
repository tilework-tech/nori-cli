#!/usr/bin/env bash
# Regenerate the `nori host` wire schema and the TypeScript types derived from it.
#
#   scripts/generate-host-wire-types.sh          regenerate the schema (cargo) and the types (node)
#   scripts/generate-host-wire-types.sh --check  fail if the checked-in types do not match the
#                                                checked-in schema (node only; the schema itself is
#                                                checked by `cargo test -p nori-cli --test host_wire_schema`)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
protocol="$root/nori-rs/nori-protocol"
schema="$protocol/schema/host-wire.schema.json"
types="$protocol/typescript/host-wire.ts"
check=false

case "${1:-}" in
  "") ;;
  --check) check=true ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac

if [[ "$check" == false ]]; then
  (cd "$root/nori-rs" && NORI_WRITE_HOST_WIRE_SCHEMA=1 cargo test -p nori-cli --test host_wire_schema --quiet -- the_checked_in_host_wire_schema_matches)
fi

(cd "$protocol/typescript" && npm ci --no-audit --no-fund --ignore-scripts --silent)

generated="$(mktemp)"
trap 'rm -f "$generated"' EXIT
# Explicit style flags keep the output independent of any Prettier config
# found above the output folder.
"$protocol/typescript/node_modules/.bin/json2ts" \
  --input "$schema" \
  --output "$generated" \
  --unreachableDefinitions \
  --additionalProperties false \
  --no-style.useTabs \
  --style.tabWidth 2 \
  --style.printWidth 100 \
  --no-style.singleQuote \
  --style.semi \
  --style.trailingComma all \
  --style.endOfLine lf \
  --bannerComment "// Generated by scripts/generate-host-wire-types.sh from nori-rs/nori-protocol/schema/host-wire.schema.json. Do not edit."

if [[ "$check" == true ]]; then
  if ! diff -u "$types" "$generated"; then
    echo "host-wire.ts is out of date; run scripts/generate-host-wire-types.sh" >&2
    exit 1
  fi
  echo "host-wire.ts is up to date"
else
  cp "$generated" "$types"
  echo "wrote $schema and $types"
fi
